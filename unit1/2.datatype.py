'''type of value store in variable'''
#NUMERIC DATATYPE
a=10
print(type(a))
b=11.2
print(type(b))

#SEQUENCE DATATYPE
c="java"
print(type(c))
d=(1,2,3)
print(type(d))
e=[1,2,3]
print(type(e))

#DICTIONARY DATATYPE
f={"name":"vaishnavi","surname":"kadam"}
print(type(f))

#SET DATATYPE
g={1,2,3}
print(type(g))

#BOOLEAN DATATYPE
a=10
b=20
c=a>b
print(type(c))
