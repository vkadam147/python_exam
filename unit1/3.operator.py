a=10
b=20
#ARITHMETIC OPERATOR
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a//b) #floor division
print(a%b)
print(a**b)

'''RELATIONAL OPERATOR'''
a=20
b=30
print(a<b)
print(a>b)
print(a<=b)
print(a>=b)
print(a!=b)
print(a==b)

'''logical operator'''
print(5>10 and 10<5)
print(10<20 or 10/0)
print(not 10>20)

'''ASSIGNMENT/COMPOUND OPERATOR'''
a = 10
print(a)

a += 5
print(a)

a -= 5
print(a)

a /= 5
print(a)

a %= 5
print(a)

a = 5
print(a)

a += 5
print(a)

a //= 5
print(a)

a **= 5
print(a)




